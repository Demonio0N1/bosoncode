export type Textos = typeof es;
export type Idioma = "sistema" | "es" | "en";

export function idiomaGuardado(): Idioma {
  try {
    const v = localStorage.getItem("idioma");
    return v === "es" || v === "en" ? v : "sistema";
  } catch {
    return "sistema";
  }
}

export function textos(idioma: Idioma): Textos {
  const efectivo = idioma === "sistema" ? (navigator.language.toLowerCase().startsWith("es") ? "es" : "en") : idioma;
  return efectivo === "es" ? es : en;
}
